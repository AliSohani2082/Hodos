"""Single entry point for the M0 (e) mastery simulation: `uv run python run.py` regenerates results/.

  --quick     3 seeds x 60 learners, minutes -> seconds, for a smoke test (numbers are NOT the committed ones)
  --golden    rewrite fixtures/bkt_golden.json (BKT-lite vectors for the TypeScript port)
  --only gate|fsrs   run one half
"""

import argparse
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--golden", action="store_true")
    ap.add_argument("--only", choices=["gate", "fsrs"])
    ap.add_argument("--out", type=Path, default=None, help="output directory (default: results/, or out/quick/ with --quick)")
    args = ap.parse_args()

    if args.golden:
        from mastery_sim import golden

        golden.write()
        print("wrote", golden.PATH)
        return 0

    out_dir = args.out or (HERE / "out" / "quick" if args.quick else HERE / "results")
    out_dir.mkdir(parents=True, exist_ok=True)
    sections = []
    t0 = time.time()
    if args.only in (None, "gate"):
        from mastery_sim import gate_report

        print("gate simulation (ALI-64)...", flush=True)
        sections.append(("Gate simulation (ALI-64)", gate_report.run_gate(out_dir, quick=args.quick)))
        print(f"  done in {time.time() - t0:.0f}s", flush=True)
    if args.only in (None, "fsrs"):
        from mastery_sim import fsrs_report

        t1 = time.time()
        print("FSRS simulation (ALI-65)...", flush=True)
        sections.append(("FSRS simulation (ALI-65)", fsrs_report.run_fsrs(out_dir, quick=args.quick)))
        print(f"  done in {time.time() - t1:.0f}s", flush=True)

    suffix = "" if args.only is None else f"_{args.only}"
    md = ["# Results: M0 spike (e), BKT-lite and FSRS simulation\n",
          "Generated by `run.py`; do not edit by hand. The generative models and assumptions are in the README.\n"]
    for title, body in sections:
        md.append(f"## {title}\n\n{body}")
    (out_dir / f"RESULTS{suffix}.md").write_text("\n".join(md))
    print("wrote", out_dir / f"RESULTS{suffix}.md", f"({time.time() - t0:.0f}s total)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
